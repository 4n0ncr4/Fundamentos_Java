package Parcial4;

public class Calculadora {
    public Calculadora() {
    }
    int sumar(int a, int b){
        return a+b;
    }
    double sumar(double a, double b){
        return a+b;
    }
    int sumar(int a, int b, int c){
        return a+b+c;
    }
    void mostrar(int a, int b, int c){
        System.out.println(a+b+c);
    }
}
